vll ans(N);
vll dp(N,-1);

int catalan[N+3];
void init() {
    catalan[0] = catalan[1] = 1;
    for (int i=2; i<=N; i++) {
        catalan[i] = 0;
        for (int j=0; j < i; j++) {
            catalan[i] += (catalan[j] * catalan[i-j-1]) % M;
            if (catalan[i] >= M) {
                catalan[i] -= M;
            }
        }
    }
}

ll func(ll n){
    if(n==1){
        return 2;
    }else if(n==0){
        return 0;
    }
    if(dp[n]!=-1){
        return dp[n];
    }
    else{
        return dp[n] = (func(n-1)+((2*(n-1)+1)*(catalan[n-1]))%M+((func(n-2)+(2*(n-1)+1) * catalan[n-2])%M)%M)%M;
    }
}

void preprocessing(){
    init();
}

void solve(){
    int n;
    cin>>n;
    cout<<func(n)<<endl;

}

